CREATE TABLE IF NOT EXISTS products (
  id UUID PRIMARY KEY,
  external_code VARCHAR(255) NOT NULL UNIQUE,
  name VARCHAR(500) NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  price NUMERIC(12,2) NOT NULL DEFAULT 0,
  discount NUMERIC(7,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS product_attributes (
  id BIGSERIAL PRIMARY KEY, product_id UUID NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  key VARCHAR(255) NOT NULL, value TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS product_images (
  id BIGSERIAL PRIMARY KEY, product_id UUID NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  url TEXT NOT NULL, path TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS imports (
  id UUID PRIMARY KEY, status VARCHAR(32) NOT NULL, total INTEGER NOT NULL DEFAULT 0,
  processed INTEGER NOT NULL DEFAULT 0, errors JSONB NOT NULL DEFAULT '[]',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), finished_at TIMESTAMPTZ
);
